"""Golden questions (tests/golden.yaml), run in order through the HTTP API.

    pytest tests/test_golden.py -q                          # TestClient, local
    pytest tests/test_golden.py -q --base-url https://...   # live server
    pytest tests/test_golden.py -q --write-baseline-doc     # also writes docs/baseline_results.md

The LLM is real here. Each question pauses 2 s so the free tier is not hammered.
Each question is run in order: the event (id 6) changes the answers for 7 to 10.
"""
import json
import os
import time
from pathlib import Path

import httpx
import pytest
import yaml

from app import seed
from app.db import connect
from app.events import DEMO_EVENT_TEXT, event_id

ROOT = Path(__file__).resolve().parent.parent
GOLDEN = yaml.safe_load((ROOT / "tests" / "golden.yaml").read_text(encoding="utf-8"))
PAUSE_S = 2
DOC = ROOT / "docs" / "baseline_results.md"


@pytest.fixture(scope="module")
def api(request):
    base_url = request.config.getoption("--base-url")
    if base_url:
        client = httpx.Client(base_url=base_url, timeout=60)
        yield client
        client.close()
        return
    from fastapi.testclient import TestClient

    from app.main import app

    with TestClient(app) as client:
        yield client


@pytest.fixture(scope="module")
def records(request):
    rows = []
    yield rows
    if request.config.getoption("--write-baseline-doc"):
        _write_doc(rows)


def _token() -> str:
    from app import config  # noqa: F401  (importing app.config loads .env)
    return os.environ.get("DEMO_TOKEN", "")


@pytest.fixture(scope="module", autouse=True)
def reset_first(api):
    resp = api.post("/reset", headers={"X-Demo-Token": _token()})
    assert resp.status_code == 200, resp.text
    yield
    # The run ends after the event, so re-seed for the tests that follow (they expect the seed).
    seed.reset(connect())


def _haystack(data: dict) -> str:
    return json.dumps({k: data.get(k) for k in ("answer", "rows", "path", "clarify")}, default=str)


def _baseline(api, question: str):
    time.sleep(PAUSE_S)
    resp = api.post("/baseline", json={"question": question})
    return resp.json() if resp.status_code == 200 else {"error": resp.text}


def _write_doc(rows):
    lines = [
        "# Baseline results: graph vs keyword RAG",
        "",
        "Generated by `pytest tests/test_golden.py -q --write-baseline-doc`.",
        "The 'Your score' column is left empty on purpose: score it by hand.",
        "",
        "| # | Question | Graph answer (tool, router) | Baseline answer (keyword RAG) | Baseline snippets (id, score, rank) | Your score |",
        "|---|---|---|---|---|---|",
    ]
    for r in rows:
        g = r["graph"]
        b = r["baseline"]
        graph_cell = f"{g.get('answer') or g.get('message') or g.get('status')}"
        if g.get("tool"):
            graph_cell += f" ({g['tool']}, {g.get('router')})"
        if r.get("event"):
            graph_cell = r["event"]
        base_cell = (b.get("answer") or f"ERROR: {b.get('error')}") if b else "n/a"
        snip_cell = ", ".join(
            f"{s['id']} ({s['score']}, rank {s['rank']})" for s in (b or {}).get("snippets", [])
        ) or "n/a"
        cells = [str(r["id"]), r["question"], graph_cell, base_cell, snip_cell, ""]
        lines.append("| " + " | ".join(c.replace("|", "/").replace("\n", " ") for c in cells) + " |")
    DOC.parent.mkdir(exist_ok=True)
    DOC.write_text("\n".join(lines) + "\n", encoding="utf-8")


@pytest.mark.parametrize("case", GOLDEN, ids=[f"golden-{c['id']}" for c in GOLDEN])
def test_golden(api, case, records, request):
    write_doc = request.config.getoption("--write-baseline-doc")

    if "event" in case:
        time.sleep(PAUSE_S)
        resp = api.post("/events", json={"text": case["event"]}, headers={"X-Demo-Token": _token()})
        assert resp.status_code == 200, resp.text
        data = resp.json()
        records.append({"id": case["id"], "question": "(event) " + case["event"], "event": _event_cell(data),
                        "graph": data, "baseline": None})
        assert data["status"] == "applied", data
        assert len(data["closed"]) == case["expect_closed"]
        assert len(data["opened"]) == case["expect_opened"]
        moved = {t["ticket_id"] for t in data["tickets_moved"]}
        assert moved == set(case["expect_tickets_moved"])
        return

    time.sleep(PAUSE_S)
    resp = api.post("/ask", json={"question": case["question"]})
    assert resp.status_code == 200, resp.text
    data = resp.json()
    base = _baseline(api, case["question"]) if write_doc else None
    records.append({"id": case["id"], "question": case["question"], "graph": data, "baseline": base})

    if "expect_tool" in case:
        assert data.get("tool") == case["expect_tool"], data
    for needle in case.get("expect_contains", []):
        assert needle in _haystack(data), f"missing {needle!r}"
    if "expect_source" in case:
        assert case["expect_source"] in [s["id"] for s in data.get("sources", [])], data.get("sources")
    if case.get("expect_source_is_event"):
        assert event_id(DEMO_EVENT_TEXT) in [s["id"] for s in data.get("sources", [])]
    if "expect_first" in case:
        assert data["rows"][0]["person"] == case["expect_first"], data["rows"]
    if "expect_clarify" in case:
        assert data["status"] == "clarify", data
        names = [c["name"] for c in data["clarify"]]
        for name in case["expect_clarify"]:
            assert name in names, names
    if case.get("expect_unknown"):
        assert data["status"] == "unknown", data


def _event_cell(data: dict) -> str:
    if data.get("status") != "applied":
        return f"{data.get('status')}: {data.get('reasons') or data.get('error')}"
    closed = ", ".join(c["service"] for c in data["closed"])
    moved = ", ".join(t["ticket_id"] for t in data["tickets_moved"])
    return f"applied: closed {len(data['closed'])} ({closed}); opened {len(data['opened'])}; moved {moved}"
